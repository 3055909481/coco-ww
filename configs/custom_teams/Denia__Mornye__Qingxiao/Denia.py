        trace = []
        last_sample = 0.0
        # 【所有判据的锚点是"HUD 在场之后过了多久", 不是"按下之后过了多久"】
        # (2026-09-07, 为了让这一格能按穿大招演出)。
        # 启动轴现在是【R 一发出去就按住】—— 而莫宁大招隐藏 HUD 288F(4.8 秒),
        # 那 4.8 秒里 is_mouse_forte_full 什么都读不到, 拿按下时刻当锚点的话
        # MOR_HOLD_BLIND(2 秒)会在演出中途就把手松开, 整发升天重击丢掉。
        # 用 HUD 当锚点: 演出期间根本不计时, HUD 一回来才开始算 ——
        # 循环轴那边 HUD 一直在, live_at 第一帧就落地, 行为跟以前一样
