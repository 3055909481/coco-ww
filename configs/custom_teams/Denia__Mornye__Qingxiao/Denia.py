                #  · on_air 更早? 不 —— 它跟"清空核心"几乎同时到;
                #  · 演出结束松一下再按给个新按下沿? 无效 —— 两轮时长 5.64/5.66,
                #    说明长按穿过演出本来就是生效的, 缺的从来不是按下沿。)
