                # 【E 还没发就一律不算】(2026-09-06 干跑抓到)。轴上这一格是
                # "3A -> E -> 重击", 而核心有可能在 E 之前就被上一轮的残留顶满 ——
                # 那时判成"重击出手了"直接返回, 这一格的 E 就整个丢了(后面 R 的
                # 能量和下一轮的核心都靠它)。所以出手判据要跟 E 绑在一起
                # a) 【核心满着 + 手一直按着 = 强化重击必然出手, 不去确认它】
                # ===== 这是 2026-09-07 连调四轮之后定下来的形状, 别再改回去 =====
