        # 给 40, 黑A/黑重击打中也给), 能量环亮只说明大招能量够。
        # Labels.denia_end_lib 是"黑大招图标"的模板(原版就靠它区分两发大招):
        #   icon=True  -> 已解锁, 那 NOFIRE 就是键被动画吞了/发晚了;
        #   icon=False -> 共形不够, 【往上游查那两发 E 打中没有】, 在这里怎么重试都白搭
        try:
            end_lib = bool(self.task.find_one(Labels.denia_end_lib))
        except Exception:
            end_lib = None
        self.macro_mark(f'denR2icon({end_lib})')
        fired = False
        attempt = 0
        retry_start = time.time()
        while self.time_elapsed_accounting_for_freeze(retry_start) < self.S_DEN_R2_CAP:
            # 【先看大招亮没亮, 亮了才发】: 对着没能量的大招连按 25 下 R 要花 1.2 秒,
            # 那段时间本来可以拿去攒能量
            ready = attempt == 0
            if not ready:
                try:
                    ready = bool(self.liberation_available())
                except Exception:
                    ready = True      # 读不到就照发, 别因为读屏失败把大招丢了
